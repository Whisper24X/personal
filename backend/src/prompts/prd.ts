/**
 * 构建 PRD 生成提示词
 * @param input MRD 内容
 * @param knowledgeContext 可选的结构化知识上下文
 * @returns PRD 生成提示词
 */
export function buildPRDPrompt(input: string, knowledgeContext?: StructuredKnowledgeContext): string {
  // 格式化知识上下文
  let knowledgeSection = '';
  let knowledgeRequirements = '';
  if (knowledgeContext && !isKnowledgeContextEmpty(knowledgeContext)) {
    const formattedKnowledge = formatStructuredKnowledge(knowledgeContext);
    knowledgeSection = `

${STRUCTURED_KNOWLEDGE_INSTRUCTION}

${formattedKnowledge}
`;
    knowledgeRequirements = `
9. **参考知识库内容**：确保与术语词典、业务规则、历史PRD保持一致
${PRD_KNOWLEDGE_REQUIREMENTS}`;
  }

  const sourceNote = knowledgeSection ? '\n- 引用知识库内容时需标注来源：> 📚 来源：[知识类型] - 文档名称' : '';

  return `基于以下市场研究文档（MRD），生成一份【研发与交互可直接执行】的产品需求文档（PRD）：

【市场研究文档（MRD）】
${input}
${knowledgeSection}

【PRD 模板格式（必须严格遵循）】
${PRD_TEMPLATE}

生成要求：
1. **严格遵循 PRD 模板结构**：主干 0-16 章必须齐全；不要新增无关的 \`##\` 级章节
2. **填充模板中的所有表格、清单、流程图**，不得留空或仅保留表头
3. **不得出现占位符或未完成标记**（如 \`<...>\`/TBD/TODO/待补充）
4. **信息不足必须写入「2.3 关键假设」**，说明假设、验证方式、风险
5. **4.3 必须提供 Mermaid 流程图**，且与 4.1/4.2 的文字流程一致
6. **5.3 关键页面说明按“用户动作 -> 系统反馈”展开**，覆盖入口、前置、输入校验、请求、成功/失败、异常、埋点/日志，并覆盖页面状态
7. **6-10 章节必须可验证**：规则、权限、安全、异常、埋点、验收、上线回滚可测试/可观测
8. 避免模糊表述；如需合理推断，明确标注为假设${knowledgeRequirements}

硬性要求：
- 输出完整 Markdown PRD，必须包含模板主干章节（0-16章）
- 内容不少于 3000 字
- 不保留任何占位符或空表格/空清单
- 章节编号和标题必须与模板完全一致
- 14.2 Go/No-Go 条件必须可执行${sourceNote}
`;
}

