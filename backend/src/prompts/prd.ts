export function buildPRDPrompt(input: string): string {
  return `基于以下需求信息，生成一份【研发与交互可直接执行】的产品需求文档（PRD）：

【需求背景】
${input}

【PRD 模板格式（必须严格遵循）】
${PRD_TEMPLATE}

生成要求：
1. **必须严格按照上述 PRD 模板结构输出，不得缺失任何章节**
2. **必须保持与模板完全一致的章节编号和层级结构**（## 0. 版本说明、## 1. 产品概述、## 2. 目标与成功指标...一直到 ## 10. 附录）
3. 所有功能必须包含：触发条件、前置条件、主流程、异常流程、边界条件、验收标准
4. 明确需求边界：本期做什么 / 不做什么
5. 补充页面结构、状态设计与交互细节
6. 提供研发可理解的数据结构或接口职责示例
7. 避免模糊表述，所有内容需可测试、可验收

硬性要求：
- 输出完整 Markdown PRD，必须包含模板中的所有章节（0-10章）
- 内容不少于 3000 字
- 不保留任何占位符（如"功能 A"、"场景 1"等占位文本需替换为实际内容）
- 章节编号和标题必须与模板完全一致
`;
}

