/**
 * 测试用例（Test Cases）提示词
 */

export const TEST_SYSTEM_PROMPT = `你是一位专业的 QA 工程师，擅长编写全面的测试用例。

你的角色是基于 PRD（产品需求文档）和代码实现，编写高质量的测试用例，确保代码质量和功能正确性。

主要职责：
- 根据 PRD 中的功能需求编写对应的测试用例
- 编写单元测试覆盖所有核心功能
- 编写集成测试验证系统交互
- 设计边界测试和异常测试
- 确保测试覆盖 PRD 中定义的所有用户故事和验收标准
- 确保测试可读性和可维护性
- 提供测试执行指南

输出格式：多个测试文件，使用主流测试框架（如 Jest, PyTest 等）。`;

export function buildTestPrompt(code: string, prd?: string): string {
    return `基于以下${prd ? 'PRD（产品需求文档）和' : ''}代码实现，编写全面的测试用例：

${prd ? `## PRD（产品需求文档）：
${prd}

**重要**：请仔细阅读 PRD 文档，确保测试用例覆盖 PRD 中定义的所有功能需求、用户故事和验收标准。每个功能点都应该有对应的测试用例。

` : ''}## 代码实现：
${code}

请编写以下类型的测试：

1. **功能测试**（基于 PRD 需求）：
   ${prd ? '- 根据 PRD 中的每个功能点编写对应的测试用例\n   - 验证用户故事（User Story）的验收标准\n   - 测试功能是否满足 PRD 中定义的需求\n   - 确保所有 PRD 中提到的功能都有测试覆盖\n' : ''}
2. **单元测试**：
   - 测试每个函数/方法的核心逻辑
   - 测试边界条件
   - 测试异常处理
   - 确保代码逻辑正确性

3. **集成测试**：
   - 测试模块间的交互
   - 测试端到端流程
   - 测试 API 接口（如适用）
   - 验证系统整体功能

4. **测试要求**：
   - 使用适当的测试框架
   - 提供清晰的测试描述（测试名称应该清晰描述测试的功能点）
   - 包含必要的 mock 和 fixture
   - 确保测试可独立运行
   ${prd ? '- 测试用例的命名和组织应该与 PRD 中的功能模块对应\n   - 每个 PRD 功能点都应该有对应的测试文件或测试套件\n' : ''}

请使用以下格式输出每个测试文件：

\`\`\`
===== FILE: path/to/test_file.ext =====
[测试文件内容]
===== END FILE =====
\`\`\`

同时提供测试运行指南：
- 如何安装测试依赖
- 如何运行测试
- 预期的测试覆盖率

**重要要求**：
- 请生成完整的测试用例，不要使用省略号（...）或注释占位符
- 至少生成 8 个完整的测试文件，覆盖所有核心功能
- 每个测试文件都要包含多个具体的测试用例
- 测试用例要包含完整的断言和验证逻辑
- 包含测试配置文件（如 jest.config.js、pytest.ini 等）
- 包含测试数据的 fixture 文件
- 确保测试覆盖率达到 80% 以上
- 所有测试代码都必须是完整可运行的，不能有未完成的部分`;
}

export default {
    TEST_SYSTEM_PROMPT,
    buildTestPrompt,
};

