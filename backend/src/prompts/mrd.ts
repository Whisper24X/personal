export function buildMRDPrompt(userIdea: string, relevantChunks?: string): string {
    const ragContext = relevantChunks
        ? `\n\n【相关历史MRD参考信息】\n${relevantChunks}\n\n请参考上述历史MRD信息，结合当前需求生成新的MRD文档。`
        : '';

    return `基于以下用户需求，创建一份详细的市场研究文档（MRD）：${ragContext}

【用户需求】
${userIdea}

【市场研究文档模板格式（必须严格遵循）】
${MRD_TEMPLATE}

生成要求：
1. **必须严格按照上述市场研究文档模板结构输出，不得缺失任何章节**
2. **必须保持与模板完全一致的章节编号和层级结构**（## 1. 需求背景与目标价值分析、## 2. 需求价值分析...一直到 ## 7. 项目范围）
3. 重点关注以下方面并体现在相应章节中：
   - 项目的核心目标价值和业务价值是什么？（章节 1）
   - 需求的优先级和重要程度如何？（章节 2）
   - 目标用户是谁？他们的痛点是什么？（章节 3）
   - 业务流程和功能逻辑是怎样的？（章节 4）
   - 市场竞品情况和我们的差异化优势是什么？（章节 5）
   - 商业可行性和风险如何？（章节 6）
   - 项目范围边界是什么？（章节 7）

硬性要求：
- 输出完整 Markdown 市场研究文档，必须包含模板中的所有章节（1-7章）
- 内容不少于 2500 字
- 不保留任何占位符（如"[描述]"、"用户类型 1"、"功能 1"等占位文本需替换为实际内容）
- 章节编号和标题必须与模板完全一致
- 每个章节都要包含充分的内容和具体的细节
- 重点关注业务价值、市场分析和用户需求，不涉及技术实现细节
`;
}

