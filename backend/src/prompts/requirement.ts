export function buildRequirementSpecPrompt(userIdea: string): string {
  return `基于以下用户需求，创建一份详细的需求说明文档：

【用户需求】
${userIdea}

【需求说明文档模板格式（必须严格遵循）】
${REQUIREMENT_SPEC_TEMPLATE}

生成要求：
1. **必须严格按照上述需求说明文档模板结构输出，不得缺失任何章节**
2. **必须保持与模板完全一致的章节编号和层级结构**（## 1. 需求概述、## 2. 用户分析、## 3. 功能需求概述...一直到 ## 9. 下一步建议）
3. 考虑以下问题并体现在相应章节中：
   - 用户真正想要解决的问题是什么？（章节 1.1、1.2）
   - 目标用户是谁？他们的痛点是什么？（章节 2）
   - 有哪些类似的产品或解决方案？（章节 4）
   - 项目的核心价值是什么？（章节 1.3、4.2）
   - 有哪些潜在的风险和挑战？（章节 8）

硬性要求：
- 输出完整 Markdown 需求说明文档，必须包含模板中的所有章节（1-9章）
- 内容不少于 2000 字
- 不保留任何占位符（如"[描述]"、"用户类型 1"、"功能 1"等占位文本需替换为实际内容）
- 章节编号和标题必须与模板完全一致
- 每个章节都要包含充分的内容和具体的细节
`;
}

