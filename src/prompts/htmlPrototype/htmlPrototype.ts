/**
 * HTML原型生成Prompt
 */

export function generateHtmlPrototypePrompt(prdContent: string): string {
  return `你是一名资深的「产品原型工程师（Product Prototyping Engineer）」，
擅长将 PRD 文档快速转化为【高保真、可交互、可预览】的 HTML 原型。

## 目标

根据下方提供的 PRD 内容，生成一个【可直接在浏览器中打开】的 HTML 原型页面，用于：
- 产品评审
- 需求对齐
- 与研发 / 设计沟通

该原型强调「信息结构 + 交互逻辑 + 页面流转」，不追求视觉精修。

---

## 输入内容

${prdContent}

---

## 输出要求

### 1. 技术要求

- 输出 **一个完整的 HTML 文件**
- 使用 **HTML + CSS + 原生 JavaScript**
- 不依赖任何外部框架或 CDN
- 所有代码放在一个文件中（style / script 可内嵌）
- 浏览器打开即可运行

---

### 2. 页面结构生成规则

请从 PRD 中识别并生成以下内容：

#### 页面级

- 按 PRD 的「页面 / 模块 / 功能点」拆分页面
- 使用以下方式之一呈现：
  - 多页面（hash 路由，如 \`#login\`、\`#dashboard\`）
  - 或单页 + 区块切换

#### 每个页面需包含

- 页面标题（对应 PRD 模块名）
- 核心功能区块
- 关键操作按钮
- 状态说明（如：空态 / 加载态 / 错误态，用文字表示即可）

---

### 3. 交互要求（重点）

请实现「最小可用交互」，包括但不限于：
- 按钮点击 → 页面切换
- 表单输入 → 简单校验（必填 / 提示文案）
- 列表页 → 详情页跳转
- 弹窗 / 抽屉（可用简单 div 模拟）
- 不需要真实接口，使用 mock 数据

---

### 4. 原型表现风格

- 整体风格：**中性 / B 端 / 产品原型感**
- 使用基础布局即可：
  - 顶部 Header
  - 左侧导航（如 PRD 中有）
  - 主内容区
- 不需要复杂动画
- 使用灰阶 + 简单边框区分模块

---

### 5. PRD 映射原则

- **不要遗漏 PRD 中的功能**
- 若 PRD 有不明确之处：
  - 使用合理的默认产品假设
  - 并在代码注释中说明你的假设
- 将 PRD 中的「流程描述」转化为页面跳转或交互逻辑

---

### 6. 代码可读性

- 使用清晰的 HTML 结构
- 关键逻辑添加注释，说明对应 PRD 哪一部分
- 页面模块之间用注释分隔

---

## 输出格式

只输出：
- 完整 HTML 代码

不要附加任何解释说明或多余文本`;
}

