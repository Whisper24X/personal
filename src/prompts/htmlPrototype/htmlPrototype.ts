export function generateMobileFirstPrompt(prdContent: string): string {
  return `请根据以下产品需求文档(PRD)，生成一个**移动优先**的HTML原型:

${prdContent}

移动优先设计要求:
1. 首先为移动设备（375px宽度）设计界面
2. 使用大号可点击按钮（最小44x44px）
3. 简化导航，使用汉堡菜单
4. 内容优先，减少不必要的装饰元素
5. 支持触摸手势（滑动、点击等）

然后再适配到更大屏幕...
`;
}

