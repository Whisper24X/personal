function serviceIdForRepo(repo: WorkspaceRepo): string {
  return basename(repo.path)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || repo.key.toLowerCase();
}

const WORKSPACE_SYNC_EXCLUDED_SEGMENTS = new Set([
  ".git",
  "node_modules",
  ".next",
  "dist",
  "build",
  "coverage",
  ".turbo",
  ".cache"
]);

function parseDeletedGitStatusPaths(output: string): string[] {
  const paths: string[] = [];
  const entries = output.split("\0").filter(Boolean);
  for (let index = 0; index < entries.length; index += 1) {
    const entry = entries[index];
    if (entry.length < 4) {
      continue;
    }
    const status = entry.slice(0, 2);
    const filePath = entry.slice(3);
    if (status.includes("R")) {
      index += 1;
    }
    if (status.includes("D")) {
      paths.push(filePath);
    }
  }
  return paths;
}

function isWorkspaceSyncPathExcluded(path: string): boolean {
  return path.split(/[\\/]/).some((segment) => WORKSPACE_SYNC_EXCLUDED_SEGMENTS.has(segment));
}

function asNonEmptyString(value: unknown): string | undefined {
  if (typeof value !== "string") {
    return undefined;
  }
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : undefined;
}

function asNonEmptySource(value: unknown): string | undefined {
  if (typeof value !== "string") {
    return undefined;
  }
  return value.trim().length > 0 ? value : undefined;
}

function resolveServiceList(config: ServiceStartupConfig | ServiceStartupFileConfig): ServiceStartupServiceConfig[] {
  if ("schemaVersion" in config) {
    const defaults = config.defaults;
    return config.services.map((service) => ({
      ...service,
      env: defaults?.env ? { ...defaults.env, ...(service.env ?? {}) } : service.env,
      startupTimeoutMs: service.startupTimeoutMs ?? defaults?.startupTimeoutMs,
      stopTimeoutMs: service.stopTimeoutMs ?? defaults?.stopTimeoutMs
    }));
  }

  return Array.isArray(config.services) ? config.services : [];
}

function resolveStopTimeoutMs(task: TitingTask): number {
  const serviceStartup = task.metadata.serviceStartup;
  if (!serviceStartup || typeof serviceStartup !== "object" || Array.isArray(serviceStartup)) {
    return 15_000;
  }

  const raw = (serviceStartup as Record<string, unknown>).stopTimeoutMs;
  return typeof raw === "number" && Number.isFinite(raw) && raw > 0 ? raw : 15_000;
}

function isProductOpenSpecTask(task: TitingTask): boolean {
  return task.agentKind === "product" || task.executor === "product" || task.driverId === "openspec-product";
}

function isProgrammingFromProduct(task: TitingTask): boolean {
  return typeof task.metadata.sourceProductTaskId === "string"
    || task.metadata.workflowRole === "programming_from_product";
}

function isBranchCheckedOutInAnotherWorktree(error: unknown): boolean {
  if (!(error instanceof EnvironmentPreparationError) || error.stage !== "checkout") {
    return false;
  }
  const detail = String(error.detail ?? error.message ?? "").toLowerCase();
  return detail.includes("already used by worktree") || detail.includes("已经被工作区");
}

