const OPEN_SPEC_GIT_EXCLUDE_PATTERNS = [
  "/openspec/.next/",
  "/openspec/**/.next/",
  "/openspec/node_modules/",
  "/openspec/**/node_modules/"
];

export class LocalWorktreeEnvironmentPlugin implements EnvironmentPlugin {
  readonly id = "git-worktree-local";
  readonly kind = "environment" as const;
  readonly priority = 100;
  readonly capabilities = ["local-worktree"];

  constructor(private readonly config: ServerConfig) {}

  async health(): Promise<PluginHealth> {
    return { healthy: true, message: `Workspace root ${this.config.workspace.root}` };
  }

  async prepareWorkspace(task: TitingTask, context?: EnvironmentContext): Promise<PreparedWorkspace> {
    const preflight = task.metadata.preflight;
    if (preflight && typeof preflight === "object" && (preflight as Record<string, unknown>).passed !== true) {
      throw new EnvironmentPreparationError("preflight", "Task preflight did not pass", null, false);
    }

    const workspacePath = this.resolveTaskWorkspacePath(task);
    const artifactsPath = join(workspacePath, "artifacts");
    const serviceStartupToolchainEnv = await detectServiceStartupToolchainEnv(process.cwd());
    // Non-interactive defaults so tool commands (npx/npm/git) never block on a
    // stdin prompt and hang the executor; task-provided env still wins.
    const env = {
      CI: "true",
      npm_config_yes: "true",
      DEBIAN_FRONTEND: "noninteractive",
      GIT_TERMINAL_PROMPT: "0",
      ...serviceStartupToolchainEnv,
      ...normalizeWorkspaceEnv(task.metadata.env)
    };
    const repoRefs = readTaskRepos(task);
    const expandSingleRepo = repoRefs.length === 1;
    const reuseExistingWorkspace = await pathExists(workspacePath);

    await mkdir(this.config.workspace.root, { recursive: true });
    await mkdir(this.config.workspace.repoCacheRoot, { recursive: true });
    let reuseWorkspace = reuseExistingWorkspace;
    if (reuseWorkspace) {
      const canReuse = await this.canReuseWorkspace(reuseWorkspace, workspacePath, repoRefs, expandSingleRepo, task.branch);
      if (!canReuse) {
        await rm(workspacePath, { recursive: true, force: true });
        reuseWorkspace = false;
      }
    }

    if (!expandSingleRepo && !reuseWorkspace) {
      await mkdir(workspacePath, { recursive: true });
    }

    const preparedRepos: WorkspaceRepo[] = [];
    if (reuseWorkspace) {
      for (const ref of repoRefs) {
        const slug = resolveRepoSlug(ref.url);
        const repoPath = expandSingleRepo ? workspacePath : join(workspacePath, slug);
        const cachePath = resolve(this.config.workspace.repoCacheRoot, hashRepo(ref.url));
        await installDependenciesIfNeeded(repoPath, env, this.config.goalRecovery.executionTimeoutMs, context?.runtimeLogger);
        preparedRepos.push({
          key: ref.key,
          url: ref.url,
          path: repoPath,
          cachePath
        });
      }
    } else {
      for (const ref of repoRefs) {
        const slug = resolveRepoSlug(ref.url);
        const repoPath = expandSingleRepo ? workspacePath : join(workspacePath, slug);
        const cachePath = resolve(this.config.workspace.repoCacheRoot, hashRepo(ref.url));
        if (await pathExists(cachePath) && !(await this.isValidMirrorCache(cachePath))) {
          await rm(cachePath, { recursive: true, force: true });
        }
        if (await pathExists(cachePath)) {
          await this.removeRegisteredWorktree(cachePath, repoPath, context);
        } else {
          await runCheckedCommand(
            "git",
            ["clone", "--mirror", ref.url, cachePath],
            this.config.workspace.root,
            process.env,
            this.config.goalRecovery.executionTimeoutMs,
            "clone",
            context?.runtimeLogger
          );
        }
        await this.fetchMirrorCache(cachePath, context);

        await rm(repoPath, { recursive: true, force: true });
        const targetRef = await this.resolveWorkspaceTargetRef(cachePath, task, ref);
        await runCheckedCommand(
          "git",
          ["--git-dir", cachePath, "worktree", "add", "--force", repoPath, targetRef],
          this.config.workspace.root,
          process.env,
          this.config.goalRecovery.executionTimeoutMs,
          "worktree",
          context?.runtimeLogger
        );
        try {
          await runCheckedCommand(
            "git",
            ["-C", repoPath, "checkout", "-B", task.branch, targetRef],
            this.config.workspace.root,
            process.env,
            this.config.goalRecovery.executionTimeoutMs,
            "checkout",
            context?.runtimeLogger
          );
        } catch (error) {
          if (!isBranchCheckedOutInAnotherWorktree(error)) {
            throw error;
          }
        }
        await installDependenciesIfNeeded(repoPath, env, this.config.goalRecovery.executionTimeoutMs, context?.runtimeLogger);
        preparedRepos.push({
          key: ref.key,
          url: ref.url,
          path: repoPath,
          cachePath
        });
      }
    }

    const validatedRepos = await this.validatePreparedRepos(preparedRepos, task.branch);
    preparedRepos.splice(0, preparedRepos.length, ...validatedRepos);

    await mkdir(artifactsPath, { recursive: true });
    const rootSkillsPath = join(workspacePath, "skills");
    const hadRootSkillsBeforeSpec = await pathExists(rootSkillsPath);
    const specResult = reuseWorkspace && await pathExists(join(artifactsPath, "workspace.json"))
      ? { documents: [], workflowPromptsPath: await this.findExistingWorkflowPromptsPath(workspacePath) }
      : await this.bootstrapOpenSpecWorkspace(task, workspacePath);
    const skillsLoad = await loadSpecSkillsIntoWorkspace(workspacePath);
    if (!hadRootSkillsBeforeSpec && await pathExists(rootSkillsPath)) {
      await rm(rootSkillsPath, { recursive: true, force: true });
    }
    await writeSkillsLoadArtifact(artifactsPath, skillsLoad);
    await installWorkspaceTooling(workspacePath, this.config, skillsLoad);
    const syncedFromHandoff = await this.syncWorkspaceFromHandoffSource(
      task,
      workspacePath,
      preparedRepos,
      env,
      context
    );
    if (syncedFromHandoff) {
      for (const repo of preparedRepos) {
        await installDependenciesIfNeeded(repo.path, env, this.config.goalRecovery.executionTimeoutMs, context?.runtimeLogger);
      }
    }

    const primary = preparedRepos[0];
    if (!primary) {
      throw new EnvironmentPreparationError("checkout", "No repositories prepared", null, false);
    }

    const serviceStartupInjectedPath = await this.materializeInjectedServicesConfig(task, preparedRepos, primary);
    const serviceStartupScaffoldPaths = await this.materializeServiceStartupScaffolds(task, preparedRepos);

    if (expandSingleRepo) {
      await this.excludeSingleRepoWorkspaceArtifacts(
        primary.path,
        [
          artifactsPath,
          ...specResult.documents.map((document) => document.localPath),
          join(workspacePath, "WORKFLOW_PROMPTS.md"),
          join(workspacePath, "task.md"),
          join(workspacePath, "knowledge", "WORKFLOW_PROMPTS.md"),
          join(workspacePath, ".cursor", "skills"),
          join(workspacePath, "node_modules"),
          join(workspacePath, ".next"),
          join(workspacePath, "pnpm-lock.yaml"),
          join(workspacePath, "package-lock.json"),
          join(workspacePath, "yarn.lock"),
          ...(serviceStartupInjectedPath ? [serviceStartupInjectedPath] : [])
        ],
        OPEN_SPEC_GIT_EXCLUDE_PATTERNS
      );
    } else if (serviceStartupInjectedPath) {
      const injectedRepo = this.findRepoForPath(preparedRepos, serviceStartupInjectedPath) ?? primary;
      await this.excludeSingleRepoWorkspaceArtifacts(injectedRepo.path, [serviceStartupInjectedPath]);
    }

    await writeFile(join(artifactsPath, "workspace.json"), JSON.stringify({
      taskId: task.id,
      workspacePath,
      repoPath: primary.path,
      cachePath: primary.cachePath,
      git: {
        isGitWorktree: primary.isGitWorktree === true,
        branch: primary.branch ?? task.branch,
        commit: primary.commit ?? null
      },
      repos: preparedRepos,
      branch: task.branch,
      workflowPromptsPath: specResult.workflowPromptsPath,
      specDocuments: specResult.documents,
      skillsLoad,
      serviceStartupInjectedPath,
      serviceStartupScaffoldPaths,
      reusedWorkspace: reuseExistingWorkspace,
      preparedAt: new Date().toISOString(),
      envKeys: Object.keys(env)
    }, null, 2));

    return {
      workspacePath,
      repoPath: primary.path,
      repos: preparedRepos,
      workflowPromptsPath: specResult.workflowPromptsPath,
      specRootPath: workspacePath,
      branch: task.branch,
      cachePath: primary.cachePath,
      artifactsPath,
      env
    };
  }

  private async materializeServiceStartupScaffolds(task: TitingTask, repos: WorkspaceRepo[]): Promise<string[]> {
    if (readTaskServiceStartup(task.metadata)) {
      return [];
    }

    if (repos.length === 0) {
      return [];
    }

    const scaffoldPaths: string[] = [];
    const isMultiRepo = repos.length > 1;
    for (const repo of repos) {
      const servicesPath = join(repo.path, ".diting", "services.yaml");
      if (await pathExists(servicesPath)) {
        continue;
      }
      await mkdir(dirname(servicesPath), { recursive: true });
      await writeFile(servicesPath, renderServiceStartupScaffold(repo, isMultiRepo));
      scaffoldPaths.push(servicesPath);
    }
    return scaffoldPaths;
  }

  private async materializeInjectedServicesConfig(
    task: TitingTask,
    repos: WorkspaceRepo[],
    primary: WorkspaceRepo
  ): Promise<string | undefined> {
    const taskConfig = readTaskServiceStartup(task.metadata);
    if (!taskConfig || taskConfig.enabled === false || (taskConfig.services && taskConfig.services.length > 0)) {
      return undefined;
    }
    if (!taskConfig.servicesYaml) {
      return undefined;
    }

    let parsed: ServiceStartupFileConfig;
    try {
      parsed = parseServiceStartupConfigYaml(taskConfig.servicesYaml);
    } catch (error) {
      const detail = error instanceof Error ? error.message : String(error);
      throw new EnvironmentPreparationError("service_startup_config", "Invalid injected servicesYaml", detail, false);
    }

    const targetRepo = this.resolveServicesYamlTargetRepo(repos, primary, parsed);
    const configPath = taskConfig.configPath ?? ".diting/services.yaml";
    const injectedPath = resolveTargetRepoPath(targetRepo.path, configPath);
    await mkdir(dirname(injectedPath), { recursive: true });
    await writeFile(injectedPath, taskConfig.servicesYaml);
    return injectedPath;
  }

  private resolveServicesYamlTargetRepo(
    repos: WorkspaceRepo[],
    primary: WorkspaceRepo,
    parsed: ServiceStartupFileConfig
  ): WorkspaceRepo {
    const repoKeys = [...new Set(parsed.services.map((service) => service.repoKey).filter((key): key is string => Boolean(key)))];
    if (repoKeys.length === 1) {
      return repos.find((repo) => repo.key === repoKeys[0]) ?? primary;
    }
    return primary;
  }

  private findRepoForPath(repos: WorkspaceRepo[], filePath: string): WorkspaceRepo | undefined {
    const resolvedFilePath = resolve(filePath);
    return repos.find((repo) => {
      const repoPath = resolve(repo.path);
      return resolvedFilePath === repoPath || resolvedFilePath.startsWith(`${repoPath}${sep}`);
    });
  }

  private async canReuseWorkspace(
    reuseExistingWorkspace: boolean,
    workspacePath: string,
    repoRefs: Array<{ key: string; url: string }>,
    expandSingleRepo: boolean,
    branch: string
  ): Promise<boolean> {
    if (!reuseExistingWorkspace) {
      return false;
    }
    for (const ref of repoRefs) {
      const repoPath = expandSingleRepo ? workspacePath : join(workspacePath, resolveRepoSlug(ref.url));
      try {
        await this.assertReusableRepo(repoPath, branch);
      } catch (error) {
        if (error instanceof EnvironmentPreparationError && error.stage === "workspace") {
          return false;
        }
        throw error;
      }
    }
    return true;
  }

  private resolveTaskWorkspacePath(task: TitingTask): string {
    const workspaceId = typeof task.metadata.workspaceId === "string" ? task.metadata.workspaceId.trim() : "";
    if (workspaceId && isProgrammingFromProduct(task)) {
      const resolved = resolve(workspaceId);
      const root = resolve(this.config.workspace.root);
      if (resolved === root || resolved.startsWith(`${root}${sep}`)) {
        return resolved;
      }
    }
    return resolve(this.config.workspace.root, `${task.id}-${task.executor}`);
  }

  private async assertReusableRepo(repoPath: string, branch: string): Promise<void> {
    if (!(await pathExists(repoPath))) {
      throw new EnvironmentPreparationError(
        "workspace",
        "Existing workspace is missing a repository path",
        repoPath,
        false
      );
    }

    const timeoutMs = this.config.goalRecovery.executionTimeoutMs;
    const gitProbe = await runCommand("git", ["-C", repoPath, "rev-parse", "--is-inside-work-tree"], repoPath, timeoutMs);
    if (gitProbe.exitCode !== 0 || gitProbe.stdout.trim() !== "true") {
      throw new EnvironmentPreparationError(
        "workspace",
        "Existing workspace repository is not a valid git worktree",
        gitProbe.stderr.trim() || gitProbe.stdout.trim() || repoPath,
        false
      );
    }

    const branchProbe = await runCommand("git", ["-C", repoPath, "branch", "--show-current"], repoPath, timeoutMs);
    const currentBranch = branchProbe.stdout.trim();
    if (branchProbe.exitCode !== 0 || currentBranch !== branch) {
      throw new EnvironmentPreparationError(
        "workspace",
        `Existing workspace branch ${currentBranch || "<detached>"} does not match task branch ${branch}`,
        repoPath,
        false
      );
    }
  }

  private async validatePreparedRepos(repos: WorkspaceRepo[], branch: string): Promise<WorkspaceRepo[]> {
    if (repos.length === 0) {
      throw new EnvironmentPreparationError("checkout", "No repositories prepared", null, false);
    }

    const validated: WorkspaceRepo[] = [];
    for (const repo of repos) {
      const git = await this.readGitWorktreeMetadata(repo.path, branch);
      validated.push({
        ...repo,
        isGitWorktree: true,
        branch: git.branch,
        commit: git.commit
      });
    }
    return validated;
  }

  private async readGitWorktreeMetadata(repoPath: string, branch: string): Promise<{ branch: string; commit: string }> {
    if (!(await pathExists(repoPath))) {
      throw new EnvironmentPreparationError(
        "workspace",
        "Prepared repository path is missing",
        repoPath,
        false
      );
    }

    const timeoutMs = this.config.goalRecovery.executionTimeoutMs;
    const gitProbe = await runCommand("git", ["-C", repoPath, "rev-parse", "--is-inside-work-tree"], repoPath, timeoutMs);
    if (gitProbe.exitCode !== 0 || gitProbe.stdout.trim() !== "true") {
      throw new EnvironmentPreparationError(
        "checkout",
        "Prepared repository is not a valid git worktree",
        gitProbe.stderr.trim() || gitProbe.stdout.trim() || repoPath,
        false
      );
    }

    const branchProbe = await runCommand("git", ["-C", repoPath, "branch", "--show-current"], repoPath, timeoutMs);
    const currentBranch = branchProbe.stdout.trim();
    if (branchProbe.exitCode !== 0 || (currentBranch && currentBranch !== branch)) {
      throw new EnvironmentPreparationError(
        "checkout",
        `Prepared repository branch ${currentBranch || "<detached>"} does not match task branch ${branch}`,
        repoPath,
        false
      );
    }

    const headProbe = await runCommand("git", ["-C", repoPath, "rev-parse", "HEAD"], repoPath, timeoutMs);
    const commit = headProbe.stdout.trim();
    if (headProbe.exitCode !== 0 || !commit) {
      throw new EnvironmentPreparationError(
        "checkout",
        "Prepared repository HEAD could not be resolved",
        headProbe.stderr.trim() || headProbe.stdout.trim() || repoPath,
        false
      );
    }

    return { branch: currentBranch || branch, commit };
  }

  private async isValidMirrorCache(cachePath: string): Promise<boolean> {
    const probe = await runCommand(
      "git",
      ["--git-dir", cachePath, "rev-parse", "--is-bare-repository"],
      this.config.workspace.root,
      this.config.goalRecovery.executionTimeoutMs
    );
    return probe.exitCode === 0 && probe.stdout.trim() === "true";
  }

  private async findExistingWorkflowPromptsPath(workspacePath: string): Promise<string | undefined> {
    const candidates = [
      join(workspacePath, "WORKFLOW_PROMPTS.md"),
      join(workspacePath, "knowledge", "WORKFLOW_PROMPTS.md")
    ];
    for (const candidate of candidates) {
      if (await pathExists(candidate)) {
        return candidate;
      }
    }
    return undefined;
  }

  private async syncWorkspaceFromHandoffSource(
    task: TitingTask,
    workspacePath: string,
    repos: WorkspaceRepo[],
    env: Record<string, string>,
    context?: EnvironmentContext
  ): Promise<boolean> {
    const sourceWorkspace = this.resolveWorkspaceSyncSource(task);
    if (!sourceWorkspace) {
      return false;
    }
    const sourcePath = this.resolveSafeWorkspaceSyncPath(sourceWorkspace, "source");
    const targetPath = this.resolveSafeWorkspaceSyncPath(workspacePath, "target");
    if (sourcePath === targetPath) {
      return false;
    }
    if (!(await pathExists(sourcePath))) {
      throw new EnvironmentPreparationError("workspace_sync", "Workspace sync source is missing", sourcePath, false);
    }

    await this.copyWorkspaceRootArtifacts(sourcePath, targetPath);
    for (const repo of repos) {
      const sourceRepoPath = await this.resolveSourceRepoPath(sourcePath, targetPath, repo);
      if (!sourceRepoPath) {
        continue;
      }
      await this.copyDirectoryOverlay(sourceRepoPath, repo.path);
      await this.applyDeletedFilesFromSourceRepo(sourceRepoPath, repo.path, env);
    }
    return true;
  }

  private resolveWorkspaceSyncSource(task: TitingTask): string | null {
    const metadata = task.metadata ?? {};
    const workspaceSync = metadata.workspaceSync;
    if (workspaceSync && typeof workspaceSync === "object" && !Array.isArray(workspaceSync)) {
      const source = asNonEmptyString((workspaceSync as Record<string, unknown>).sourceWorkspaceId);
      if (source) {
        return source;
      }
    }
    const qualityWorkspaceId = asNonEmptyString(metadata.qualityWorkspaceId);
    if (qualityWorkspaceId && (task.agentKind === "programming" || task.executor === "programming")) {
      return qualityWorkspaceId;
    }
    const handoff = metadata.implementationHandoff;
    if (handoff && typeof handoff === "object" && !Array.isArray(handoff)) {
      const workspaceId = asNonEmptyString((handoff as Record<string, unknown>).workspaceId);
      if (workspaceId && (task.agentKind === "quality" || task.executor === "quality")) {
        return workspaceId;
      }
    }
    return null;
  }

  private resolveSafeWorkspaceSyncPath(path: string, label: "source" | "target"): string {
    const resolved = resolve(path);
    const root = resolve(this.config.workspace.root);
    if (resolved !== root && !resolved.startsWith(`${root}${sep}`)) {
      throw new EnvironmentPreparationError(
        "workspace_sync",
        `Workspace sync ${label} is outside workspace root`,
        resolved,
        false
      );
    }
    return resolved;
  }

  private async copyWorkspaceRootArtifacts(sourceWorkspace: string, targetWorkspace: string): Promise<void> {
    const entries = [
      "openspec",
      "WORKFLOW_PROMPTS.md",
      join("knowledge", "WORKFLOW_PROMPTS.md"),
      "artifacts"
    ];
    for (const entry of entries) {
      const sourcePath = join(sourceWorkspace, entry);
      if (!(await pathExists(sourcePath))) {
        continue;
      }
      const targetPath = join(targetWorkspace, entry);
      await rm(targetPath, { recursive: true, force: true });
      await mkdir(dirname(targetPath), { recursive: true });
      await cp(sourcePath, targetPath, {
        recursive: true,
        force: true,
        filter: (candidate) => this.shouldCopyWorkspaceSyncPath(sourcePath, candidate)
      });
    }
  }

  private async resolveSourceRepoPath(
    sourceWorkspace: string,
    targetWorkspace: string,
    targetRepo: WorkspaceRepo
  ): Promise<string | null> {
    const relativeRepoPath = relative(targetWorkspace, targetRepo.path);
    const candidates = [
      relativeRepoPath && !relativeRepoPath.startsWith("..") && !isAbsolute(relativeRepoPath)
        ? join(sourceWorkspace, relativeRepoPath)
        : null,
      sourceWorkspace,
      join(sourceWorkspace, basename(targetRepo.path))
    ].filter((candidate): candidate is string => Boolean(candidate));

    for (const candidate of candidates) {
      const resolved = resolve(candidate);
      if (await this.isGitWorkspacePath(resolved)) {
        return resolved;
      }
    }
    return null;
  }

  private async isGitWorkspacePath(candidate: string): Promise<boolean> {
    if (!(await pathExists(candidate))) {
      return false;
    }
    const result = await runCommand(
      "git",
      ["-C", candidate, "rev-parse", "--is-inside-work-tree"],
      candidate,
      this.config.goalRecovery.executionTimeoutMs
    );
    return result.exitCode === 0 && result.stdout.trim() === "true";
  }

  private async copyDirectoryOverlay(sourcePath: string, targetPath: string): Promise<void> {
    await mkdir(targetPath, { recursive: true });
    await cp(sourcePath, targetPath, {
      recursive: true,
      force: true,
      filter: (candidate) => this.shouldCopyWorkspaceSyncPath(sourcePath, candidate)
    });
  }

  private shouldCopyWorkspaceSyncPath(sourceRoot: string, candidate: string): boolean {
    const relativePath = relative(sourceRoot, candidate);
    if (!relativePath) {
      return true;
    }
    const segments = relativePath.split(sep);
    return !segments.some((segment) => WORKSPACE_SYNC_EXCLUDED_SEGMENTS.has(segment));
  }

  private async applyDeletedFilesFromSourceRepo(
    sourceRepoPath: string,
    targetRepoPath: string,
    env: Record<string, string>
  ): Promise<void> {
    const result = await runCommand(
      "git",
      ["-C", sourceRepoPath, "status", "--porcelain", "--untracked-files=all", "-z"],
      sourceRepoPath,
      this.config.goalRecovery.executionTimeoutMs,
      env
    );
    if (result.exitCode !== 0) {
      throw new EnvironmentPreparationError(
        "workspace_sync",
        "Failed to read workspace sync source git status",
        result.stderr.trim() || result.stdout.trim(),
        false
      );
    }
    for (const deletedPath of parseDeletedGitStatusPaths(result.stdout)) {
      if (isWorkspaceSyncPathExcluded(deletedPath)) {
        continue;
      }
      await rm(join(targetRepoPath, deletedPath), { recursive: true, force: true });
    }
  }

  private async bootstrapOpenSpecWorkspace(task: TitingTask, workspacePath: string) {
    const isProductTask = isProductOpenSpecTask(task);
    if (readTaskSpecAttachments(task).length > 0) {
      const result = await materializeSpecDocuments(task, workspacePath, this.config, {
        requireOpenSpecDirectory: !isProductTask
      });
      if (!isProductTask) {
        return result;
      }
      await mkdir(join(workspacePath, "openspec"), { recursive: true });
      await writeFile(join(workspacePath, "task.md"), renderProductTaskContext(task));
      return {
        ...result,
        workflowPromptsPath: result.workflowPromptsPath ?? await this.findExistingWorkflowPromptsPath(workspacePath)
      };
    }
    if (!isProductTask) {
      return materializeSpecDocuments(task, workspacePath, this.config);
    }
    await mkdir(join(workspacePath, "openspec"), { recursive: true });
    await writeFile(join(workspacePath, "task.md"), renderProductTaskContext(task));
    return { documents: [], workflowPromptsPath: await this.findExistingWorkflowPromptsPath(workspacePath) };
  }

  private async excludeSingleRepoWorkspaceArtifacts(
    repoPath: string,
    paths: string[],
    extraPatterns: string[] = []
  ): Promise<void> {
    const excludePathResult = await runCommand(
      "git",
      ["-C", repoPath, "rev-parse", "--git-path", "info/exclude"],
      repoPath,
      this.config.goalRecovery.executionTimeoutMs
    );
    if (excludePathResult.exitCode !== 0) {
      throw new EnvironmentPreparationError(
        "workspace",
        "Unable to resolve git exclude path for single-repo workspace",
        excludePathResult.stderr || excludePathResult.stdout,
        false
      );
    }

    const patterns = [
      ...paths
        .map((path) => this.toRepoExcludePattern(repoPath, path))
        .filter((pattern): pattern is string => Boolean(pattern)),
      ...extraPatterns
    ];
    if (patterns.length === 0) {
      return;
    }

    const excludePath = excludePathResult.stdout.trim();
    await mkdir(dirname(excludePath), { recursive: true });
    await appendFile(excludePath, `\n# Titing workspace-managed files\n${[...new Set(patterns)].join("\n")}\n`);
  }

  private toRepoExcludePattern(repoPath: string, path: string): string | null {
    const relativePath = relative(repoPath, path);
    if (!relativePath || relativePath === ".." || relativePath.startsWith(`..${sep}`)) {
      return null;
    }
    const normalized = relativePath.split(sep).join("/");
    const suffix = normalized.includes(".") ? "" : "/";
    return `/${normalized}${suffix}`;
  }

  async startTargetServices(
    task: TitingTask,
    workspace: PreparedWorkspace,
    context?: {
      roundExecuted?: boolean;
      beforeCommand?: (command: string[]) => Promise<void>;
    }
  ): Promise<PreparedWorkspace> {
    const discovered = await discoverServiceStartupConfig(task, workspace);
    if (!discovered.enabled) {
      return workspace;
    }

    const services = resolveServiceList(discovered.config);
    if (services.length === 0) {
      return workspace;
    }

    const running = await startTargetServicesLifecycle({
      workspace,
      services,
      artifactsPath: workspace.artifactsPath,
      configSource: discovered.configSource,
      allowReuse: context?.roundExecuted !== true,
      beforeCommand: context?.beforeCommand
    });
    return {
      ...workspace,
      services: {
        schemaVersion: 1,
        configSource: discovered.configSource,
        running
      }
    };
  }

  async stopTargetServices(task: TitingTask, workspace: PreparedWorkspace): Promise<PreparedWorkspace> {
    const runningServices = workspace.services?.running;
    if (!runningServices || runningServices.length === 0) {
      return workspace;
    }

    const stopped = await stopTargetServicesLifecycle({
      services: runningServices,
      artifactsPath: workspace.artifactsPath,
      stopTimeoutMs: resolveStopTimeoutMs(task)
    });
    return {
      ...workspace,
      services: {
        schemaVersion: 1,
        configSource: workspace.services?.configSource ?? "inferred",
        running: stopped
      }
    };
  }

  async cleanupWorkspace(task: TitingTask, workspace: PreparedWorkspace): Promise<void> {
    const shouldDelete = task.status === "succeeded" && this.config.workspace.cleanupOnSuccess;
    if (!shouldDelete) {
      return;
    }

    try {
      for (const repo of workspace.repos) {
        await this.removeRegisteredWorktree(repo.cachePath, repo.path);
      }
    } finally {
      await rm(workspace.workspacePath, { recursive: true, force: true });
    }
  }

  private async removeRegisteredWorktree(
    cachePath: string,
    repoPath: string,
    context?: EnvironmentContext
  ): Promise<void> {
    try {
      await runCheckedCommand(
        "git",
        ["--git-dir", cachePath, "worktree", "remove", "--force", repoPath],
        this.config.workspace.root,
        process.env,
        this.config.goalRecovery.executionTimeoutMs,
        "cleanup",
        context?.runtimeLogger
      );
    } catch (error) {
      if (!(error instanceof EnvironmentPreparationError) || error.stage !== "cleanup") {
        throw error;
      }
    }
  }

  private async fetchMirrorCache(cachePath: string, context?: EnvironmentContext): Promise<void> {
    await this.normalizeMirrorFetchConfig(cachePath, context);
    await runCheckedCommand(
      "git",
      [
        "--git-dir",
        cachePath,
        "fetch",
        "origin",
        "--prune",
        "+refs/heads/*:refs/remotes/origin/*",
        "+refs/tags/*:refs/tags/*"
      ],
      this.config.workspace.root,
      process.env,
      this.config.goalRecovery.executionTimeoutMs,
      "fetch",
      context?.runtimeLogger
    );
  }

  private async normalizeMirrorFetchConfig(cachePath: string, context?: EnvironmentContext): Promise<void> {
    const timeoutMs = this.config.goalRecovery.executionTimeoutMs;
    await runCommand(
      "git",
      ["--git-dir", cachePath, "config", "--unset-all", "remote.origin.mirror"],
      this.config.workspace.root,
      timeoutMs
    );
    await runCommand(
      "git",
      ["--git-dir", cachePath, "config", "--unset-all", "remote.origin.fetch"],
      this.config.workspace.root,
      timeoutMs
    );
    await runCheckedCommand(
      "git",
      ["--git-dir", cachePath, "config", "remote.origin.mirror", "false"],
      this.config.workspace.root,
      process.env,
      timeoutMs,
      "fetch",
      context?.runtimeLogger
    );
    await runCheckedCommand(
      "git",
      ["--git-dir", cachePath, "config", "--add", "remote.origin.fetch", "+refs/heads/*:refs/remotes/origin/*"],
      this.config.workspace.root,
      process.env,
      timeoutMs,
      "fetch",
      context?.runtimeLogger
    );
    await runCheckedCommand(
      "git",
      ["--git-dir", cachePath, "config", "--add", "remote.origin.fetch", "+refs/tags/*:refs/tags/*"],
      this.config.workspace.root,
      process.env,
      timeoutMs,
      "fetch",
      context?.runtimeLogger
    );
  }

  private async resolveWorkspaceTargetRef(
    cachePath: string,
    task: TitingTask,
    repoRef: { key: string; url: string }
  ): Promise<string> {
    const timeoutMs = this.config.goalRecovery.executionTimeoutMs;
    const repoLabel = `${repoRef.key} (${repoRef.url})`;
    try {
      return await resolveBranchRef(cachePath, task.branch, timeoutMs);
    } catch (error) {
      if (!(error instanceof EnvironmentPreparationError) || error.stage !== "checkout") {
        throw error;
      }
      if (!isAutoGeneratedTaskBranch(task.metadata)) {
        throw error;
      }
      const baseBranch = await detectDefaultBaseBranch(cachePath, timeoutMs, {
        bareGitDir: true,
        fallback: this.config.workspace.prBaseBranchFallback ?? undefined
      });
      try {
        return await resolveBranchRef(cachePath, baseBranch, timeoutMs);
      } catch (fallbackError) {
        if (fallbackError instanceof EnvironmentPreparationError && fallbackError.stage === "checkout") {
          throw new EnvironmentPreparationError(
            "checkout",
            `Default task branch ${task.branch} could not be created from origin/${baseBranch} for ${repoLabel}`,
            fallbackError.detail,
            false
          );
        }
        throw fallbackError;
      }
    }
  }
}

type ServiceStartupToolchainDiscovery = {
  basePath?: string;
  shellPath?: string;
  kratosPath?: string;
  goPath?: string;
  goBin?: string;
};

export function buildServiceStartupToolchainEnv(discovery: ServiceStartupToolchainDiscovery): Record<string, string> {
  const pathDirs = uniqueNonEmpty([
    discovery.kratosPath ? pathDirname(discovery.kratosPath) : undefined,
    discovery.goBin,
    discovery.goPath ? join(discovery.goPath, "bin") : undefined,
    ...splitPath(discovery.shellPath),
    ...splitPath(discovery.basePath)
  ]);
  const env: Record<string, string> = {};
  if (pathDirs.length > 0) {
    env.PATH = pathDirs.join(":");
  }
  if (discovery.goPath) {
    env.GOPATH = discovery.goPath;
  }
  if (discovery.goBin) {
    env.GOBIN = discovery.goBin;
  }
  return env;
}

async function detectServiceStartupToolchainEnv(cwd: string): Promise<Record<string, string>> {
  const shell = process.env.SHELL || "/bin/zsh";
  const script = [
    "printf '__PATH__=%s\\n' \"$PATH\"",
    "printf '__KRATOS__=%s\\n' \"$(command -v kratos 2>/dev/null || true)\"",
    "if command -v go >/dev/null 2>&1; then",
    "  printf '__GOPATH__=%s\\n' \"$(go env GOPATH 2>/dev/null || true)\"",
    "  printf '__GOBIN__=%s\\n' \"$(go env GOBIN 2>/dev/null || true)\"",
    "fi"
  ].join("\n");

  try {
    const result = await runCommand(shell, ["-lc", script], cwd, 5_000);
    const discovered = parseServiceStartupToolchainOutput(result.stdout);
    return buildServiceStartupToolchainEnv({
      basePath: process.env.PATH,
      shellPath: discovered.PATH,
      kratosPath: discovered.KRATOS,
      goPath: discovered.GOPATH,
      goBin: discovered.GOBIN
    });
  } catch {
    return buildServiceStartupToolchainEnv({ basePath: process.env.PATH });
  }
}

function parseServiceStartupToolchainOutput(stdout: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of stdout.split(/\r?\n/)) {
    const match = line.match(/^__(PATH|KRATOS|GOPATH|GOBIN)__=(.*)$/);
    if (match && match[2].trim().length > 0) {
      result[match[1]] = match[2].trim();
    }
  }
  return result;
}

function splitPath(value: string | undefined): string[] {
  if (!value) {
    return [];
  }
  return value.split(":").filter((item) => item.trim().length > 0);
}

function uniqueNonEmpty(values: Array<string | undefined>): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const value of values) {
    const trimmed = value?.trim();
    if (!trimmed || seen.has(trimmed)) {
      continue;
    }
    seen.add(trimmed);
    result.push(trimmed);
  }
  return result;
}

function readTaskServiceStartup(metadata: Record<string, unknown>): ServiceStartupConfig | null {
  const raw = metadata.serviceStartup;
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    return null;
  }

  const record = raw as Record<string, unknown>;
  return {
    enabled: typeof record.enabled === "boolean" ? record.enabled : undefined,
    configPath: asNonEmptyString(record.configPath),
    servicesYaml: asNonEmptySource(record.servicesYaml),
    services: Array.isArray(record.services) ? record.services as ServiceStartupServiceConfig[] : undefined
  };
}

function resolveTargetRepoPath(repoPath: string, configPath: string): string {
  if (isAbsolute(configPath)) {
    throw new EnvironmentPreparationError(
      "service_startup_config",
      "Injected servicesYaml configPath must be relative to the target repository",
      configPath,
      false
    );
  }

  const repoRoot = resolve(repoPath);
  const targetPath = resolve(repoRoot, configPath);
  if (targetPath !== repoRoot && !targetPath.startsWith(`${repoRoot}${sep}`)) {
    throw new EnvironmentPreparationError(
      "service_startup_config",
      "Injected servicesYaml configPath must stay inside the target repository",
      configPath,
      false
    );
  }
  return targetPath;
}

