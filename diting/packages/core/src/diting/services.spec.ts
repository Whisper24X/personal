async function expectTransition(
  harness: ReturnType<typeof createServicesHarness>,
  taskId: string,
  from: TaskStatus,
  to: TaskStatus,
  reason: string
): Promise<void> {
  const transitions = await harness.services.listTaskTransitions(taskId);
  expect(transitions.some((item) => item.from === from && item.to === to && item.reason === reason)).toBe(true);
}

function createServicesHarness(input: Parameters<typeof createHarness>[0] = { tasks: [], executions: [] }) {
  const harness = createHarness(input);
  let taskCounter = 0;
  return {
    ...harness,
    async createReadyTask(): Promise<TitingTask> {
      taskCounter += 1;
      const task = createTask({ id: `ready-task-${taskCounter}`, status: "ready" });
      harness.tasks.set(task.id, cloneExistingTask(task));
      return task;
    },
    async createActiveTask(): Promise<TitingTask> {
      taskCounter += 1;
      const task = createTask({ id: `active-task-${taskCounter}`, status: "active" });
      harness.tasks.set(task.id, cloneExistingTask(task));
      return task;
    },
    runOneSchedulerTick(): Promise<void> {
      return harness.services.runSchedulerTick();
    }
  };
}

function createHarness(input: {
  tasks: TitingTask[];
  executions: Array<ExecutionResult | Error | Promise<ExecutionResult>>;
  completionGateResults?: Array<Awaited<ReturnType<CompletionGatePlugin["evaluate"]>>>;
  completionGateEnabled?: boolean;
  qualityResults?: Array<Awaited<ReturnType<QualityPlugin["evaluate"]>>>;
  qualityEnabled?: boolean;
  agent?: AgentRecord;
  agents?: AgentRecord[];
  agentOfflineTimeoutMs?: number;
  environmentRetryLimit?: number;
  executionRetryLimit?: number;
  executionHeartbeatIntervalMs?: number;
  environmentError?: Error;
  workspaceOverride?: PreparedWorkspace;
  pulledTasks?: TitingTask[];
  humanReplies?: HumanReply[];
  childRepairIssues?: Array<{ taskId: string; failureHash: string; stopReason: unknown }>;
  childRepairIssueError?: Error;
  childRepairReplies?: NonNullable<TaskIntegrationPlugin["pullHumanRepairIssues"]> extends (tasks: TitingTask[]) => Promise<infer Replies>
    ? Replies
    : never;
  openSpecReviews?: Array<{ taskId: string; changeId: string; revision: string; idempotencyKey: string; openspecPath?: string }>;
  openSpecReviewReplies?: OpenSpecReviewIssueReply[];
  productAgentEnabled?: boolean;
  qualityAgentEnabled?: boolean;
  enableNeedsHumanLoop?: boolean;
  enableOpenSpecReviewGate?: boolean;
  governancePlugin?: ObservabilityGovernancePlugin;
  createPullRequests?: (task: TitingTask, workspace: PreparedWorkspace) => Promise<PullRequestRecord[]>;
  runPreflight?: (task: TitingTask) => Promise<import("@diting/plugin-api").TaskPreflightResult>;
}) {
  let now = new Date("2026-05-11T00:00:00.000Z");
  const tasks = new Map(input.tasks.map((task) => [task.id, cloneExistingTask(task)]));
  const transitions: TaskTransition[] = [];
  const logs: ExecutionLogRecord[] = [];
  const executions = new Map<string, ExecutionRecord>();
  const evalResults: EvalResult[] = [];
  const repairGoals = new Map<string, RepairGoal>();
  const runAttemptRecords = new Map<string, RunAttempt>();
  const runAttemptRepo = new InMemoryRunAttemptRepository(runAttemptRecords);
  const humanReviews = new Map<string, HumanReview>();
  const pluginConfigs = new Map<string, import("@diting/plugin-api").PluginConfig>();
  const events: Array<{
    id: string;
    schemaVersion: string;
    traceId: string;
    taskId?: string;
    executionId?: string;
    pluginId?: string;
    agentId?: string;
    eventType: string;
    data?: Record<string, unknown>;
  }> = [];
  const initialAgents = input.agents ?? [input.agent ?? createAgent()];
  const agentRecords = new Map(initialAgents.map((agent) => [agent.id, { ...agent }]));
  const agent = agentRecords.values().next().value as AgentRecord;
  const reportedResults: Array<{ taskId: string; externalId: string | null; summary: string }> = [];
  const reportedNeedsHuman: Array<{ taskId: string; externalId: string | null; payload: NeedsHumanPayload }> = [];
  const intervalCallbacks: Array<() => void> = [];

  const executionPlugin = createExecutionPlugin(input.executions);
  const productAgentPlugin = createProductAgentPlugin(input.executions);
  const qualityAgentPlugin = createQualityAgentPlugin(input.executions);
  const completionGatePlugin = createCompletionGatePlugin(input.completionGateResults ?? []);
  const qualityPlugin = createQualityPlugin(input.qualityResults ?? []);
  const environmentPlugin = createEnvironmentPlugin(input.environmentError, input.workspaceOverride);

  const services = new TitingServices({
    tasks: new InMemoryTaskRepository(tasks),
    runAttempts: runAttemptRepo,
    taskTransitions: {
      append: async (transition) => {
        transitions.push(transition);
      },
      listByTask: async (taskId) => transitions.filter((item) => item.taskId === taskId),
      listByTraceId: async (traceId) => transitions.filter((item) => item.traceId === traceId)
    },
    executions: new InMemoryExecutionRepository(executions),
    executionLogs: {
      append: async (log) => {
        logs.push(log);
      },
      listByTask: async (taskId) => logs.filter((item) => item.taskId === taskId),
      listByExecution: async (executionId) => logs.filter((item) => item.executionId === executionId)
    },
    agentLeases: new InMemoryAgentLeaseRepository(),
    agents: new InMemoryAgentRepository(agentRecords),
    repairGoals: {
      upsert: async (goal) => {
        repairGoals.set(goal.taskId, goal);
      },
      getByTaskId: async (taskId) => repairGoals.get(taskId) ?? null
    },
    humanReviews: {
      create: async (review) => {
        humanReviews.set(review.taskId, review);
      },
      save: async (review) => {
        humanReviews.set(review.taskId, review);
      },
      getLatestByTask: async (taskId) => humanReviews.get(taskId) ?? null,
      listByTask: async (taskId) => {
        const review = humanReviews.get(taskId);
        return review ? [review] : [];
      }
    },
    evalResults: {
      create: async (result) => {
        evalResults.push(result);
      },
      listByTask: async (taskId) => evalResults.filter((item) => item.taskId === taskId)
    },
    pluginConfigs: {
      list: async () => [...pluginConfigs.values()],
      getByPluginId: async (pluginId) => pluginConfigs.get(pluginId) ?? null,
      upsert: async (config) => {
        pluginConfigs.set(config.pluginId, config);
      }
    },
    events: {
      publish: async (event) => {
        events.push({
          id: event.id,
          schemaVersion: event.schemaVersion,
          traceId: event.traceId,
          taskId: event.taskId,
          executionId: event.executionId,
          pluginId: event.pluginId,
          agentId: event.agentId,
          eventType: event.eventType,
          data: event.data
        });
      }
    },
    runtime: new PluginRuntime([
      createTaskIntegrationPlugin(
        input.pulledTasks ?? [],
        input.humanReplies ?? [],
        reportedResults,
        reportedNeedsHuman,
        input.childRepairIssues,
        input.childRepairIssueError,
        input.childRepairReplies,
        input.openSpecReviews,
        input.openSpecReviewReplies
      ),
      environmentPlugin,
      executionPlugin,
      ...(input.productAgentEnabled ? [productAgentPlugin] : []),
      ...(input.qualityAgentEnabled ? [qualityAgentPlugin] : []),
      ...(input.completionGateEnabled === false ? [] : [completionGatePlugin]),
      ...(input.qualityEnabled === false ? [] : [qualityPlugin]),
      ...(input.governancePlugin ? [input.governancePlugin] : []),
      createLogPlugin()
    ] as RuntimePlugin[]),
    now: () => now,
    createId: createIdFactory(),
    agentOfflineTimeoutMs: input.agentOfflineTimeoutMs,
    environmentRetryLimit: input.environmentRetryLimit,
    executionRetryLimit: input.executionRetryLimit,
    enableNeedsHumanLoop: input.enableNeedsHumanLoop,
    enableOpenSpecReviewGate: input.enableOpenSpecReviewGate,
    executionHeartbeatIntervalMs: input.executionHeartbeatIntervalMs,
    createPullRequests: input.createPullRequests,
    runPreflight: input.runPreflight,
    setIntervalFn: (callback) => {
      intervalCallbacks.push(callback);
      return callback;
    },
    clearIntervalFn: () => undefined
  });

  return {
    services,
    agent,
    agents: agentRecords,
    executions,
    tasks,
    transitions,
    logs,
    evalResults,
    repairGoals,
    runAttempts: runAttemptRepo,
    humanReviews,
    events,
    environmentPlugin,
    executionPlugin,
    productAgentPlugin,
    qualityAgentPlugin,
    completionGatePlugin,
    qualityPlugin,
    createPullRequests: input.createPullRequests,
    reportedResults,
    reportedNeedsHuman,
    setNow: (value: Date) => {
      now = value;
    },
    tickHeartbeat: () => {
      for (const callback of intervalCallbacks) {
        callback();
      }
    }
  };
}

class InMemoryTaskRepository implements TaskRepository {
  constructor(private readonly tasks: Map<string, TitingTask>) {}

  async create(task: TitingTask): Promise<void> {
    this.tasks.set(task.id, cloneExistingTask(task));
  }

  async save(task: TitingTask): Promise<void> {
    this.tasks.set(task.id, cloneExistingTask(task));
  }

  async getById(id: string): Promise<TitingTask | null> {
    return cloneTask(this.tasks.get(id) ?? null);
  }

  async getByExternalId(source: string, externalId: string): Promise<TitingTask | null> {
    const found = [...this.tasks.values()].find((task) => task.source === source && task.externalId === externalId) ?? null;
    return cloneTask(found);
  }

  async listByTraceId(traceId: string): Promise<TitingTask[]> {
    return [...this.tasks.values()]
      .filter((task) => task.traceId === traceId)
      .sort((left, right) => left.createdAt.getTime() - right.createdAt.getTime())
      .map((task) => cloneTask(task) as TitingTask);
  }

  async list(query: { status?: TaskStatus; executor?: string } = {}): Promise<TitingTask[]> {
    return [...this.tasks.values()]
      .filter((task) => (query.status ? task.status === query.status : true))
      .filter((task) => (query.executor ? task.executor === query.executor : true))
      .map((task) => cloneTask(task) as TitingTask);
  }

  async claimQueued(id: string, startedAt: Date): Promise<TitingTask | null> {
    const task = this.tasks.get(id);
    if (!task || task.status !== "ready") {
      return null;
    }
    task.status = "active";
    task.startedAt = task.startedAt ?? startedAt;
    task.updatedAt = startedAt;
    this.tasks.set(task.id, cloneExistingTask(task));
    return cloneExistingTask(task);
  }
}

class InMemoryRunAttemptRepository implements RunAttemptRepository {
  constructor(private readonly attempts: Map<string, RunAttempt>) {}

  async create(attempt: RunAttempt): Promise<void> {
    this.attempts.set(attempt.id, { ...attempt });
  }

  async save(attempt: RunAttempt): Promise<void> {
    this.attempts.set(attempt.id, { ...attempt });
  }

  async getById(id: string): Promise<RunAttempt | null> {
    const attempt = this.attempts.get(id);
    return attempt ? { ...attempt } : null;
  }

  async getLatestByTask(taskId: string): Promise<RunAttempt | null> {
    return [...this.attempts.values()]
      .filter((item) => item.taskId === taskId)
      .sort((left, right) => right.startedAt.getTime() - left.startedAt.getTime())[0] ?? null;
  }

  async list(query: { taskId?: string; agentId?: string; stage?: RunAttempt["stage"]; limit?: number } = {}) {
    return [...this.attempts.values()]
      .filter((item) => (query.taskId ? item.taskId === query.taskId : true))
      .filter((item) => (query.agentId ? item.agentId === query.agentId : true))
      .filter((item) => (query.stage ? item.stage === query.stage : true))
      .slice(0, query.limit ?? 50)
      .map((item) => ({ ...item }));
  }

  async listByTask(taskId: string): Promise<RunAttempt[]> {
    return this.list({ taskId });
  }
}

