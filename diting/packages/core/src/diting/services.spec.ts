class InMemoryAgentRepository implements AgentRepository {
  constructor(private readonly agents: Map<string, AgentRecord>) {}

  async upsert(agent: AgentRecord): Promise<void> {
    const existing = this.agents.get(agent.id);
    if (existing) {
      Object.assign(existing, agent);
      return;
    }
    this.agents.set(agent.id, { ...agent });
  }

  async list(): Promise<AgentRecord[]> {
    return [...this.agents.values()].map((agent) => ({ ...agent }));
  }

  async getIdle(executor: string): Promise<AgentRecord | null> {
    const agent = [...this.agents.values()].find((candidate) => candidate.status === "idle" && candidate.executor === executor);
    return agent ? { ...agent } : null;
  }

  async getById(id: string): Promise<AgentRecord | null> {
    const agent = this.agents.get(id);
    return agent ? { ...agent } : null;
  }

  async claimIdle(executor: string, taskId: string, now: Date): Promise<AgentRecord | null> {
    const agent = [...this.agents.values()].find((candidate) => candidate.status === "idle" && candidate.executor === executor);
    if (!agent) {
      return null;
    }
    agent.status = "busy";
    agent.taskId = taskId;
    agent.updatedAt = now;
    agent.lastHeartbeatAt = now;
    return { ...agent };
  }

  async claimIdleById(id: string, taskId: string, now: Date): Promise<AgentRecord | null> {
    const agent = this.agents.get(id);
    if (!agent || agent.status !== "idle") {
      return null;
    }
    agent.status = "busy";
    agent.taskId = taskId;
    agent.updatedAt = now;
    agent.lastHeartbeatAt = now;
    return { ...agent };
  }
}

function createEnvironmentPlugin(error?: Error, workspaceOverride?: PreparedWorkspace) {
  const calls: {
    prepareWorkspace: number;
    cleanupWorkspace: number;
    startTargetServices?: number;
    stopTargetServices?: number;
  } = {
    prepareWorkspace: 0,
    cleanupWorkspace: 0
  };
  return {
    id: "env",
    kind: "environment" as const,
    priority: 100,
    capabilities: ["local"],
    calls,
    health: async () => ({ healthy: true, message: "ok" }),
    prepareWorkspace: async () => {
      calls.prepareWorkspace += 1;
      if (error) {
        throw error;
      }
      return workspaceOverride ?? createPreparedWorkspace();
    },
    startTargetServices: async (task: TitingTask, workspace: PreparedWorkspace) => {
      const serviceStartup = task.metadata.serviceStartup;
      if (
        !serviceStartup
        || typeof serviceStartup !== "object"
        || Array.isArray(serviceStartup)
        || !Array.isArray((serviceStartup as Record<string, unknown>).services)
      ) {
        return workspace;
      }
      calls.startTargetServices = (calls.startTargetServices ?? 0) + 1;
      return {
        ...workspace,
        services: {
          schemaVersion: 1,
          configSource: "task",
          running: [
            {
              id: "backend",
              pid: 3001,
              cwd: workspace.repoPath,
              command: ["npm", "run", "start:dev"],
              healthUrl: "http://127.0.0.1:3000/health",
              startedAt: "2026-05-11T00:00:00.000Z",
              readyAt: "2026-05-11T00:00:01.000Z",
              status: "ready"
            }
          ]
        }
      } satisfies PreparedWorkspace;
    },
    stopTargetServices: async (_task: TitingTask, workspace: PreparedWorkspace) => {
      if (!workspace.services?.running.length) {
        return workspace;
      }
      calls.stopTargetServices = (calls.stopTargetServices ?? 0) + 1;
      return {
        ...workspace,
        services: workspace.services
          ? {
              ...workspace.services,
              running: workspace.services.running.map((service) => ({
                ...service,
                status: "stopped" as const
              }))
            }
          : undefined
      } satisfies PreparedWorkspace;
    },
    cleanupWorkspace: async () => {
      calls.cleanupWorkspace += 1;
    }
  };
}

